/**
 * Station-scope discriminator — pure predicate tests.
 *
 * `isStationScopedName` / `stationCityContext` (tokens.ts) are the shared
 * policy primitives behind every station-into-city KB guard:
 *   - worker.ts `blocksStationCanonicalSwap` + `isAcceptableAlias`
 *   - merge.ts `mergeKnownEntities` refuse-gate
 *   - merge-probe.ts `findMergeCandidates` prefilter
 *
 * The fixtures mirror a bare-city KB row carrying station aliases (e.g. 'New
 * York City' carrying LaGuardia aliases, 'Milan' carrying Malpensa aliases)
 * plus the variants `stationAliasesFor` (stage1-normalize/weather-stations.ts)
 * generates, plus the sports-venue names that must NOT be classified as
 * station-scoped.
 */
import { describe, test, expect } from 'bun:test';
import { isStationScopedName, stationCityContext } from './tokens.js';

describe('isStationScopedName — station/venue keyword scope', () => {
  test('weather-station subjects from Stage 1 are station-scoped', () => {
    // canonical "<Station>, <City>" forms (the Stage-1 discriminator)
    expect(isStationScopedName('LaGuardia Airport, New York City')).toBe(true);
    expect(isStationScopedName('Malpensa International Airport, Milan')).toBe(true);
    expect(isStationScopedName('Central Park, New York City')).toBe(true);
    expect(isStationScopedName('Masroor Airbase, Karachi')).toBe(true);
    // bare station variants generated by stationAliasesFor
    expect(isStationScopedName('LaGuardia Airport')).toBe(true);
    expect(isStationScopedName('LaGuardia International Airport')).toBe(true);
    expect(isStationScopedName('Beijing Capital International Airport')).toBe(true);
    expect(isStationScopedName('Warsaw Chopin Airport')).toBe(true);
    // other station kinds
    expect(isStationScopedName('Penn Station')).toBe(true);
    expect(isStationScopedName('Griffith Observatory')).toBe(true);
    expect(isStationScopedName('Miami Downtown')).toBe(true);
  });

  test('bare city / location / team names are NOT station-scoped', () => {
    expect(isStationScopedName('New York City')).toBe(false);
    expect(isStationScopedName('Milan')).toBe(false);
    expect(isStationScopedName('Chicago')).toBe(false);
    expect(isStationScopedName('Manila')).toBe(false);
    expect(isStationScopedName('New York City FC')).toBe(false);
  });

  test('bare sports venues do NOT trip the comma-gated venue keywords', () => {
    // park/field/garden are venue words only WITH a ", <city>" context —
    // bare club/stadium names stay out of scope.
    expect(isStationScopedName('Goodison Park')).toBe(false);
    expect(isStationScopedName('Queens Park Rangers')).toBe(false);
    expect(isStationScopedName('Madison Square Garden')).toBe(false);
    expect(isStationScopedName('Love Field')).toBe(false);
    // one-word containments never match (\b boundary)
    expect(isStationScopedName('Springfield')).toBe(false);
    expect(isStationScopedName('Sunderland')).toBe(false);
  });

  test('comma context activates the venue keywords', () => {
    expect(isStationScopedName('Central Park, New York City')).toBe(true);
    expect(isStationScopedName('Love Field, Dallas')).toBe(true);
  });
});

describe('stationCityContext — the ", <city>" tail of a station-scoped name', () => {
  test('extracts the city tail from Stage-1 station subjects', () => {
    expect(stationCityContext('LaGuardia Airport, New York City')).toBe('New York City');
    expect(stationCityContext('Malpensa International Airport, Milan')).toBe('Milan');
    expect(stationCityContext('Central Park, New York City')).toBe('New York City');
  });

  test('null for bare stations (no comma tail) and non-station names', () => {
    expect(stationCityContext('LaGuardia Airport')).toBeNull();
    expect(stationCityContext('New York City')).toBeNull();
    expect(stationCityContext('Goodison Park')).toBeNull();
  });
});
